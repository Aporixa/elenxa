#!/usr/bin/env bash
# Elenxa installer (hardened local build): ① Docker (built locally)  ② local build
#
# Nothing here downloads installers or prebuilt images: Docker must already be
# installed, the elenxa image is built from this checkout, and all services bind
# to 127.0.0.1 on the host.
set -euo pipefail
cd "$(cd "$(dirname "$0")" && pwd)"

info(){ printf '\033[36m[*]\033[0m %s\n' "$*"; }
ok(){   printf '\033[32m[+]\033[0m %s\n' "$*"; }
warn(){ printf '\033[33m[!]\033[0m %s\n' "$*"; }
die(){  printf '\033[31m[x]\033[0m %s\n' "$*" >&2; exit 1; }
ask(){  local p="$1" d="${2:-}" a; read -rp "$p${d:+ [$d]}: " a; echo "${a:-$d}"; }
# 32 alphanumeric chars from the kernel CSPRNG (openssl if available).
rand(){
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c 32
  else
    head -c 48 /dev/urandom | base64 | tr -dc 'A-Za-z0-9' | head -c 32
  fi
}

ensure_docker(){
  if command -v docker >/dev/null 2>&1 && docker compose version >/dev/null 2>&1; then
    ok "docker and docker compose found"; return
  fi
  die "docker / docker compose not found. Install them from your OS package manager and re-run."
}

# ── ① Docker (local build) ──────────────────────
install_docker(){
  ensure_docker
  [ -d vendor ] || die "vendor/ missing: run 'go mod vendor' first (the image builds Go offline from vendor/)"
  if [ ! -f .env ]; then
    ( umask 077
      {
        echo "# Generated by install.sh — keep private (chmod 600)."
        echo "POSTGRES_USER=elenxa"
        echo "POSTGRES_PASSWORD=$(rand)"
        echo "POSTGRES_DB=elenxa"
        echo ""
        echo "# LLM (optional; can also be configured in the UI)"
        echo "ANTHROPIC_API_KEY="
        echo "OPENAI_API_KEY="
        echo "ELENXA_LLM_PROVIDER="
        echo "ELENXA_LLM_MODEL="
        echo "ELENXA_LLM_BASE_URL="
        echo "ELENXA_LLM_PROXY="
        echo ""
        echo "# Extra Host header values to accept besides localhost/127.0.0.1 (comma-separated)"
        echo "ELENXA_ALLOWED_HOSTS="
        echo "# DNS resolvers for enrichment as ip:port, comma-separated (empty = /etc/resolv.conf)"
        echo "ELENXA_DNS_RESOLVERS="
      } > .env )
    ok "Generated .env with a random POSTGRES_PASSWORD"
  else
    info "Using existing .env"
    grep -q '^POSTGRES_PASSWORD=..*' .env || die ".env has no POSTGRES_PASSWORD; set one (e.g. openssl rand -base64 32)"
  fi
  chmod 600 .env

  info "Building the elenxa image locally…"
  docker compose build
  info "Starting…"
  docker compose up -d
  ok "Started → http://127.0.0.1:8787 (localhost only)"
  echo
  info "First-run setup token (needed on the setup page):"
  echo "    docker compose logs elenxa | grep -i setup"
  echo "    docker compose exec elenxa cat /app/keys/setup-token"
  info "Logs: docker compose logs -f elenxa"
}

# ── ② Local build ───────────────────────────────
install_local(){
  echo "Connect to an existing PostgreSQL (e.g. a local server on 127.0.0.1)."
  DB_HOST="$(ask 'Host' 127.0.0.1)"
  DB_PORT="$(ask 'Port' 5432)"
  DB_USER="$(ask 'User' elenxa)"
  DB_PASS="$(ask 'Password' '')"
  DB_NAME="$(ask 'Database' elenxa)"
  DB_SSL="$(ask 'sslmode (disable/require)' disable)"

  ( umask 077
    cat > config.json <<JSON
{
  "database": {
    "host": "${DB_HOST}",
    "port": ${DB_PORT},
    "user": "${DB_USER}",
    "password": "${DB_PASS}",
    "dbname": "${DB_NAME}",
    "sslmode": "${DB_SSL}"
  }
}
JSON
  )
  chmod 600 config.json
  ok "Wrote config.json"

  command -v go >/dev/null 2>&1 || die "Go not found (>= 1.26 required)"
  ok "Go: $(go version)"
  [ -d vendor ] || die "vendor/ missing: run 'go mod vendor' first"
  export GOFLAGS=-mod=vendor GOPROXY=off GOTOOLCHAIN=local CGO_ENABLED=0
  export NEXT_TELEMETRY_DISABLED=1

  command -v npm >/dev/null 2>&1 || die "npm not found (needed to build the embedded web UI)"
  info "Building the web UI (static export)…"
  ( cd web && npm ci --ignore-scripts && npm run build:static )
  rm -rf server/webui/dist && cp -r web/out server/webui/dist
  info "Building binaries…"
  go build -tags embedui -trimpath -ldflags="-s -w" -o elenxa ./cmd/elenxa
  go build -trimpath -ldflags="-s -w" -o elenxa-browser-mcp ./cmd/elenxa-browser-mcp
  ok "Built ./elenxa and ./elenxa-browser-mcp"

  info "Starting on 127.0.0.1… (Ctrl-C to quit)"
  info "The first-run setup token is printed in the log below and written to setup-token next to the elenxa binary (or \$ELENXA_KEY_DIR)."
  exec ./elenxa -addr 127.0.0.1:8787 -proxy 127.0.0.1:8788
}

echo "=============================="
echo "  Elenxa install (hardened local build)"
echo "  1) Docker (image built locally)"
echo "  2) Local build (go + npm)"
echo "=============================="
case "$(ask 'Choose' 1)" in
  1) install_docker ;;
  2) install_local ;;
  *) die "invalid choice" ;;
esac
